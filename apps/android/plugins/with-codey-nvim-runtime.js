const {
  AndroidConfig,
  createRunOncePlugin,
  withAndroidManifest,
  withGradleProperties,
  withSettingsGradle
} = require('expo/config-plugins')

const ALL_FILES_PERMISSION = 'android.permission.MANAGE_EXTERNAL_STORAGE'
const UNUSED_EXPO_PERMISSIONS = [
  'android.permission.READ_EXTERNAL_STORAGE',
  'android.permission.SYSTEM_ALERT_WINDOW',
  'android.permission.VIBRATE',
  'android.permission.WRITE_EXTERNAL_STORAGE'
]
const DEV_CLIENT_NATIVE_MODULES = [
  'expo-dev-client',
  'expo-dev-launcher',
  'expo-dev-menu',
  'expo-dev-menu-interface',
  'expo-json-utils',
  'expo-manifests',
  'expo-updates-interface'
]
const BUNDLED_NVIM_NATIVE_LIBRARIES = [
  'libandroid-support.so',
  'libcodey_nvim.so',
  'libiconv.so',
  'liblpeg-5.1.so',
  'libluajit-5.1.so',
  'libluv.so',
  'libtree-sitter.so',
  'libunibilium.so',
  'libutf8proc.so',
  'libuv.so'
].map((libraryName) => `**/${libraryName}`)
const DO_NOT_STRIP_PROPERTY = 'android.packagingOptions.doNotStrip'
const GRADLE_JVM_ARGS_PROPERTY = 'org.gradle.jvmargs'
const GRADLE_METASPACE_ARGUMENT = '-XX:MaxMetaspaceSize=1024m'
const SETTINGS_GRADLE_MARKER = '// @generated by with-codey-nvim-runtime'

function setProperty(properties, key, value) {
  const filtered = properties.filter((item) => item.key !== key)
  filtered.push({ type: 'property', key, value })
  return filtered
}

function appendCsvProperty(properties, key, values) {
  const existingValues = properties
    .filter((item) => item.key === key)
    .flatMap((item) => String(item.value ?? '').split(','))
    .map((value) => value.trim())
    .filter(Boolean)
  const mergedValues = [...new Set([...existingValues, ...values])]
  return setProperty(properties, key, mergedValues.join(','))
}

function configureGradleJvmArgs(properties) {
  const existing = [...properties]
    .reverse()
    .find((item) => item.key === GRADLE_JVM_ARGS_PROPERTY)
  const jvmArguments = String(existing?.value ?? '-Xmx2048m')
    .split(/\s+/)
    .filter(Boolean)
    .filter((argument) => !argument.startsWith('-XX:MaxMetaspaceSize='))

  jvmArguments.push(GRADLE_METASPACE_ARGUMENT)
  return setProperty(properties, GRADLE_JVM_ARGS_PROPERTY, jvmArguments.join(' '))
}

function configureGradleProperties(properties) {
  let result = configureGradleJvmArgs(properties)
  result = setProperty(result, 'android.minSdkVersion', '30')
  result = setProperty(result, 'reactNativeArchitectures', 'arm64-v8a')
  result = appendCsvProperty(result, DO_NOT_STRIP_PROPERTY, BUNDLED_NVIM_NATIVE_LIBRARIES)
  return setProperty(result, 'expo.useLegacyPackaging', 'true')
}

function configureManifest(manifest) {
  AndroidConfig.Permissions.addPermission(manifest, ALL_FILES_PERMISSION)
  AndroidConfig.Manifest.ensureToolsAvailable(manifest)
  AndroidConfig.Permissions.addBlockedPermissions(manifest, UNUSED_EXPO_PERMISSIONS)
  const permissions = manifest.manifest['uses-permission'] ?? []
  let foundAllFilesPermission = false
  manifest.manifest['uses-permission'] = permissions.filter((permission) => {
    if (permission.$?.['android:name'] !== ALL_FILES_PERMISSION) return true
    if (foundAllFilesPermission) return false
    foundAllFilesPermission = true
    return true
  })
  const application = AndroidConfig.Manifest.getMainApplicationOrThrow(manifest)
  application.$['android:extractNativeLibs'] = 'true'
  return manifest
}

function configureStandaloneSettingsGradle(contents) {
  if (contents.includes(SETTINGS_GRADLE_MARKER)) return contents

  const marker = 'expoAutolinking.useExpoModules()'
  if (!contents.includes(marker)) {
    throw new Error(`Unable to configure the standalone build: ${marker} was not found in settings.gradle`)
  }

  const modules = DEV_CLIENT_NATIVE_MODULES.map((moduleName) => `'${moduleName}'`).join(', ')
  return contents.replace(
    marker,
    `${SETTINGS_GRADLE_MARKER}\nexpoAutolinking.exclude = [${modules}]\n${marker}`
  )
}

function withCodeyNvimRuntime(config) {
  const withProperties = withGradleProperties(config, (propertiesConfig) => {
    propertiesConfig.modResults = configureGradleProperties(propertiesConfig.modResults)
    return propertiesConfig
  })
  const withManifest = withAndroidManifest(withProperties, (manifestConfig) => {
    manifestConfig.modResults = configureManifest(manifestConfig.modResults)
    return manifestConfig
  })
  if (process.env.CODEY_BUILD_PROFILE !== 'standalone') return withManifest

  return withSettingsGradle(withManifest, (settingsConfig) => {
    settingsConfig.modResults.contents = configureStandaloneSettingsGradle(
      settingsConfig.modResults.contents
    )
    return settingsConfig
  })
}

const plugin = createRunOncePlugin(withCodeyNvimRuntime, 'with-codey-nvim-runtime', '1.0.0')

module.exports = plugin
module.exports.ALL_FILES_PERMISSION = ALL_FILES_PERMISSION
module.exports.DEV_CLIENT_NATIVE_MODULES = DEV_CLIENT_NATIVE_MODULES
module.exports.UNUSED_EXPO_PERMISSIONS = UNUSED_EXPO_PERMISSIONS
module.exports.configureGradleProperties = configureGradleProperties
module.exports.configureManifest = configureManifest
module.exports.configureStandaloneSettingsGradle = configureStandaloneSettingsGradle
